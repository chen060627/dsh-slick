// Builds ./client.js by inlining src/format.js into src/client-body.js.
//
// The browser module table loads one file per plugin, so relative imports are
// not available; keeping the pure logic in src/format.js and concatenating it
// here gives us a testable module under Node and a single-file client bundle.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const format = readFileSync(join(root, 'src', 'format.js'), 'utf8')
const body = readFileSync(join(root, 'src', 'client-body.js'), 'utf8')

const banner = `// dsh-slick — generated by scripts/build.mjs. Do not edit by hand.
// Sources: src/format.js + src/client-body.js
`

writeFileSync(join(root, 'client.js'), `${banner}\n${format}\n\n${body}`, 'utf8')
console.log('client.js written')
