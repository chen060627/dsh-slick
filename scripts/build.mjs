// Builds ./client.js by inlining src/format.js and src/codex-slider.js into src/client-body.js.
//
// The browser module table loads one file per plugin, so relative imports are
// not available; keeping the pure logic in src/format.js and concatenating it
// here gives us a testable module under Node and a single-file client bundle.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const format = readFileSync(join(root, 'src', 'format.js'), 'utf8')
const slider = readFileSync(join(root, 'src', 'codex-slider.js'), 'utf8')
const body = readFileSync(join(root, 'src', 'client-body.js'), 'utf8')

const banner = `// dsh-slick — generated by scripts/build.mjs. Do not edit by hand.
// Sources: src/format.js + src/client-body.js (+ src/codex-slider.js inlined at the marker)
`

const MARKER = '/*__CODEX_SLIDER__*/'
if (!body.includes(MARKER)) {
  throw new Error('src/client-body.js is missing the /*__CODEX_SLIDER__*/ marker')
}

// The vendored slider must live inside the module factory (it calls require("react")),
// so it is spliced in at the marker rather than concatenated at the top.
const merged = body.replace(MARKER, slider)

writeFileSync(join(root, 'client.js'), `${banner}\n${format}\n\n${merged}`, 'utf8')
console.log('client.js written')